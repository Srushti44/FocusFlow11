function getLocalArticles(): Article[] {
  const stored = localStorage.getItem('focusflow_articles');
  if (stored) {
    try {
      return JSON.parse(stored);
    } catch {
      // fallback
    }
  }
  localStorage.setItem('focusflow_articles', JSON.stringify(FALLBACK_ARTICLES));
  return FALLBACK_ARTICLES;
}

function saveLocalArticles(articles: Article[]) {
  localStorage.setItem('focusflow_articles', JSON.stringify(articles));
}

