def test_summary_simplifies_difficult_solipsism_text():
    res = client.post("/api/summary", json={
        "text": SOLIPSISM_TEXT,
        "title": "The Epistemological Impasse of Ontological Solipsism"
    })
    assert res.status_code == 200
    data = res.json()
    assert "tldr" in data
    tldr = data["tldr"]
    # Verify that the summary is in plain English and NOT copying the dense opening sentence verbatim
    assert "inexorable conundrum" not in tldr.lower()
    assert "hermetic refutation" not in tldr.lower()
    assert "epiphenomenal projection" not in tldr.lower()
    # Verify central idea is explained
    assert "solipsism" in tldr.lower()
    assert "mind" in tldr.lower()
    assert len(data.get("key_takeaways", [])) == 3
    for t in data["key_takeaways"]:
        assert len(t.split()) >= 6
        assert "phantasmagoric simulacra" not in t.lower()


