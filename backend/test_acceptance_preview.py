import asyncio
import json
from backend.ai_service import (
    generate_summary, generate_concepts, generate_quiz,
    generate_flashcards, simplify_text_explanation, ask_about_text
)

title = "The Epistemological Impasse of Ontological Solipsism"
text = (
    "The inexorable conundrum of radical ontological solipsism resides in its hermetic refutation of external reality, "
    "positing instead that the totality of cosmic existence is merely an epiphenomenal projection of the individual, "
    "insular psyche. This metaphysical doctrine asserts that the ego is the sole veridical entity in existence, "
    "thereby rendering all external phenomena, alterity, and objective material substrate nothing more than "
    "phantasmagoric simulacra generated by an isolated consciousness. To engage in the teleological interrogation of "
    "this framework is to confront an insurmountable epistemological impasse. Because all sensory data must be "
    "mediated through the subjective apparatus of the observer, one cannot proffer an unmediated, objective validation "
    "of an extra-mental universe without committing a egregious logical petition principii. Consequently, the solipsist "
    "remains perpetually entombed within the panopticon of their own cognitive architecture, completely unable to discern "
    "whether the external cosmos possesses intrinsic ontological validity or if it is merely a specious, dream-like "
    "configuration born of an idiosyncratic, auto-generated hallucination."
)

async def run_acceptance():
    print("=" * 60)
    print("RUNNING STEP 3 ACCEPTANCE TEST GENERATION PREVIEW")
    print("=" * 60)

    s = await generate_summary(text, title)
    print("\n--- SUMMARY ---")
    print("TLDR:", s["tldr"])
    print("Detailed:", s.get("detailed_explanation"))
    print("Takeaways:")
    for t in s["key_takeaways"]:
        print(f"  • {t}")
    print("Outline:")
    for o in s["cognitive_outline"]:
        print(f"  - {o['section']}: {o['takeaway']}")

    concepts = await generate_concepts(text, title)
    print(f"\n--- CONCEPTS ({len(concepts)}) ---")
    for c in concepts:
        print(f"[{c['term']}]: {c['definition']}")
        if c.get("analogy"):
            print(f"   Analogy: {c['analogy']}")

    quiz = await generate_quiz(text, title)
    print(f"\n--- QUIZ ({len(quiz)}) ---")
    for q in quiz:
        print(f"Q: {q['question']}")
        correct_ans = q["options"][q["correct_answer_index"]]
        print(f"   Answer: {correct_ans}")
        print(f"   Explanation: {q['explanation']}")

    flashcards = await generate_flashcards(text, title)
    print(f"\n--- FLASHCARDS ({len(flashcards)}) ---")
    for fc in flashcards:
        print(f"Card: {fc['front']} -> {fc['back']}")

    chat = await ask_about_text("Give me an analogy to explain why we cannot prove the outside world exists.", text, title)
    print("\n--- ASK AI ---")
    print(chat["answer"])

    print("\n" + "=" * 60)
    print("ACCEPTANCE TEST PREVIEW COMPLETE!")
    print("=" * 60)

if __name__ == "__main__":
    asyncio.run(run_acceptance())
